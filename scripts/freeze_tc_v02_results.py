#!/usr/bin/env python3
"""Freeze the clean TC schema-v3 evaluation as a checksummed paper artifact."""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--report",
        type=Path,
        default=Path("outputs/tropical_cyclone_bt/gauge_track1/evaluation.json"),
    )
    parser.add_argument(
        "--html",
        type=Path,
        default=Path("outputs/tropical_cyclone_bt/gauge_track1/evaluation.html"),
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("case_studies/tropical_cyclone_bt/final_results"),
    )
    args = parser.parse_args()

    report_path = args.report.resolve()
    html_path = args.html.resolve()
    output_dir = args.output_dir.resolve()
    report = json.loads(report_path.read_text(encoding="utf-8"))
    if report.get("schema") != "gauge_climate.evaluation.v3":
        raise ValueError("Only a schema-v3 evaluation can be frozen for v0.2.")
    if report.get("metadata", {}).get("package_version") != "0.2.0":
        raise ValueError("The report was not generated by gauge-climate 0.2.0.")

    output_dir.mkdir(parents=True, exist_ok=True)
    targets = {
        "evaluation.json": report_path,
        "evaluation_full.html": html_path,
    }
    for name, source in targets.items():
        if not source.is_file():
            raise FileNotFoundError(source)
        shutil.copy2(source, output_dir / name)

    artifacts = {
        name: {
            "sha256": _sha256(output_dir / name),
            "bytes": (output_dir / name).stat().st_size,
        }
        for name in sorted(targets)
    }
    manifest = {
        "schema": "gauge_climate.artifact_manifest.v2",
        "report_schema": report["schema"],
        "package_version": report["metadata"]["package_version"],
        "config_hash": report["metadata"].get("config_hash"),
        "artifacts": artifacts,
    }
    manifest_path = output_dir / "manifest.json"
    manifest_path.write_text(
        json.dumps(manifest, indent=2) + "\n",
        encoding="utf-8",
    )
    print(
        json.dumps(
            {
                "output_dir": str(output_dir),
                "manifest": str(manifest_path),
                "artifacts": artifacts,
            },
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
